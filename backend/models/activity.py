"""
EngageAI Backend — models/activity.py
SQLAlchemy ORM models for activity events and predictions.
"""

from datetime import datetime
from sqlalchemy import Column, Integer, String, Float, DateTime, Text, ForeignKey
from sqlalchemy.orm import relationship
from backend.database.db import Base


class ActivityEvent(Base):
    """
    Raw activity events generated by the frontend.
    Batched and sent every 15–30 seconds or on meaningful milestones.
    """
    __tablename__ = "activity_events"

    id         = Column(Integer, primary_key=True, index=True)
    student_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    content_id = Column(Integer, ForeignKey("learning_contents.id"), nullable=True)
    quiz_id    = Column(Integer, ForeignKey("quizzes.id"), nullable=True)

    event_type = Column(String(50), nullable=False)
    timestamp  = Column(DateTime, default=datetime.utcnow)
    duration   = Column(Integer, nullable=True)    # seconds of engagement
    week_index = Column(Integer, nullable=True)    # 0=pre-course, 1-39=weeks
    metadata_json = Column(Text, nullable=True)    # JSON blob for extra context

    # Relationships
    student = relationship("User", back_populates="activity_events", foreign_keys=[student_id])


class Prediction(Base):
    """
    Cached prediction result per student.
    Invalidated and re-computed after meaningful new activity.
    """
    __tablename__ = "predictions"

    id                   = Column(Integer, primary_key=True, index=True)
    student_id           = Column(Integer, ForeignKey("users.id"), nullable=False, unique=True)
    predicted_class      = Column(Integer, nullable=True)     # 0 | 1 | 2
    engagement_level     = Column(String(20), nullable=True)  # Low | Medium | High
    low_probability      = Column(Float, nullable=True)
    medium_probability   = Column(Float, nullable=True)
    high_probability     = Column(Float, nullable=True)
    confidence           = Column(Float, nullable=True)       # max probability
    total_activity_count = Column(Integer, default=0)
    prediction_timestamp = Column(DateTime, nullable=True)
    is_sufficient        = Column(Integer, default=0)  # 0=not enough activity yet

    # Relationships
    student = relationship("User", back_populates="predictions")
